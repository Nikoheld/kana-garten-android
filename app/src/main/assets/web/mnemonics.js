const COMBINATION_GROUPS = new Set([
  "ky",
  "sh",
  "ch",
  "ny",
  "hy",
  "my",
  "ry",
  "gy",
  "j",
  "by",
  "py",
]);

export function getKanaMnemonic(kana) {
  const direct = BASIC_MNEMONICS[kana.glyph];
  if (direct) {
    const [emoji, label, shape] = VISUAL_CUES[kana.glyph];
    return {
      title: `Bild für ${kana.glyph}`,
      text: direct,
      tip: `Verbinde das Bild laut mit „${kana.primary}“.`,
      visual: {
        type: "shape",
        emoji,
        label,
        shape,
      },
    };
  }

  const voiced = VOICED_RULES[kana.groupId];
  if (voiced) {
    const index = Number(kana.id.split(":").at(-1));
    const baseGlyph = ROW_GLYPHS[kana.script][voiced.baseRow][index];
    const [emoji, label, shape] = VISUAL_CUES[baseGlyph];
    return {
      title: `${baseGlyph} wird zu ${kana.glyph}`,
      text: `${BASIC_MNEMONICS[baseGlyph]} ${voiced.rule}`,
      tip: `Sieh zuerst ${baseGlyph}, dann das Zusatzzeichen – zusammen liest du „${kana.primary}“.`,
      visual: {
        type: "modifier",
        emoji,
        label,
        shape,
        baseGlyph,
        modifier: kana.groupId === "p" ? "゜" : "゛",
      },
    };
  }

  if (COMBINATION_GROUPS.has(kana.groupId)) {
    const characters = [...kana.glyph];
    const smallKana = characters.at(-1);
    const baseKana = characters.slice(0, -1).join("");
    const smallSound = {
      ゃ: "ya",
      ゅ: "yu",
      ょ: "yo",
      ャ: "ya",
      ュ: "yu",
      ョ: "yo",
    }[smallKana];
    return {
      title: `${baseKana} + kleines ${smallKana}`,
      text: `Das kleine ${smallKana} sitzt wie ein Beifahrer neben ${baseKana}. Es wird nicht einzeln gesprochen, sondern zieht den Laut ${smallSound} direkt an den ersten Kana-Laut heran.`,
      tip: `Sprich beide ohne Pause in einem Zug: „${kana.primary}“.`,
      visual: {
        type: "combination",
        baseGlyph: baseKana,
        smallGlyph: smallKana,
        resultGlyph: kana.glyph,
        label: "Laute verschmelzen",
        shape: `Das kleine ${smallKana} bleibt sichtbar kleiner als ${baseKana}.`,
      },
    };
  }

  return {
    title: `Merke dir ${kana.glyph}`,
    text: `Schreibe ${kana.glyph} einmal groß in die Luft und sprich dabei „${kana.primary}“. Bewegung und Laut werden so miteinander verknüpft.`,
    tip: `Achte besonders auf den Anfang und das Ende des Strichverlaufs.`,
    visual: {
      type: "shape",
      emoji: "✍️",
      label: "Luftschrift",
      shape: "Verfolge die Form langsam mit deinem Zeigefinger.",
    },
  };
}
